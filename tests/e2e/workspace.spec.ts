import { test, expect } from '@playwright/test';
import { resolve } from 'node:path';
import { readdir, readFile } from 'node:fs/promises';

test('PDF → chapter → cached AI note → knowledge → Obsidian export',async({page})=>{
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');await page.getByRole('button',{name:'先离线使用'}).click();
  await page.getByRole('button',{name:'我的教材',exact:true}).click();
  page.once('dialog',dialog=>dialog.accept(resolve(process.cwd(),'../../tests/fixtures/sample.pdf')));
  await page.getByRole('button',{name:'导入教材',exact:true}).click();
  await page.getByLabel('课程名称').fill('电路基础');await page.getByRole('button',{name:'确认导入'}).click();
  await expect(page.getByRole('heading',{name:'sample',exact:true})).toHaveCount(2);
  await page.getByRole('button',{name:'阅读与分章',exact:true}).last().click();
  const canvas=page.getByLabel('PDF 页面预览');
  await expect(canvas).toBeVisible();
  await expect.poll(()=>canvas.evaluate(element=>(element as HTMLCanvasElement).width)).toBeGreaterThan(300);
  const toolbar=page.getByLabel('选择教材');
  const toolbarBox=await toolbar.boundingBox();const canvasBox=await canvas.boundingBox();
  expect(canvasBox!.y).toBeGreaterThan(toolbarBox!.y+toolbarBox!.height);
  await page.getByLabel('结束页',{exact:true}).fill('2');await page.getByRole('button',{name:'拆分并提取文字'}).click();
  await page.getByRole('button',{name:'生成章节笔记'}).click();
  await expect(page.getByRole('dialog',{name:'使用已生成的内容'})).toBeVisible();
  await page.getByRole('button',{name:'使用缓存',exact:true}).click();
  await expect(page.getByLabel('笔记标题',{exact:true})).toHaveValue('第一章');
  await page.getByLabel('知识主题',{exact:true}).fill('电路基础, 欧姆定律');
  await page.getByRole('button',{name:'Markdown 原文',exact:true}).click();
  const original='欧姆定律：电流 = 电压 / 电阻。';
  await page.getByLabel('笔记正文',{exact:true}).fill(original);
  await page.getByRole('button',{name:'富文本',exact:true}).click();
  const rich=page.getByRole('textbox',{name:'笔记正文',exact:true});
  await expect(rich).toContainText(original);
  await rich.click();await page.keyboard.press('ControlOrMeta+A');
  await page.getByRole('button',{name:'加粗',exact:true}).click();
  await expect(rich.locator('strong')).toHaveText(original);
  await page.getByRole('button',{name:'Markdown 原文',exact:true}).click();
  await expect(page.getByLabel('笔记正文',{exact:true})).toHaveValue(`**${original}**`);
  const todo='核对欧姆定律';
  await page.getByLabel('笔记正文',{exact:true}).fill(`**${original}**\n\n- [ ] ${todo}\n- [x] 验证适用条件`);
  await page.getByRole('button',{name:'富文本',exact:true}).click();
  const checkbox=rich.getByRole('checkbox').first();
  await expect(checkbox).not.toBeChecked();
  await expect(rich.getByRole('checkbox').nth(1)).toBeChecked();
  const checkboxBox=await checkbox.boundingBox();
  const todoBox=await rich.getByText(todo,{exact:true}).boundingBox();
  expect(checkboxBox).not.toBeNull();expect(todoBox).not.toBeNull();
  expect(checkboxBox!.x+checkboxBox!.width).toBeLessThan(todoBox!.x);
  expect(Math.abs((checkboxBox!.y+checkboxBox!.height/2)-(todoBox!.y+todoBox!.height/2))).toBeLessThanOrEqual(3);
  await checkbox.check();await expect(checkbox).toBeChecked();
  await page.getByRole('button',{name:'Markdown 原文',exact:true}).click();
  await expect(page.getByLabel('笔记正文',{exact:true})).toHaveValue(`**${original}**\n\n- [x] ${todo}\n- [x] 验证适用条件`);
  await page.getByRole('button',{name:'保存笔记'}).click();
  await expect(page.getByRole('status')).toContainText('笔记已保存');
  await page.getByLabel('搜索笔记').fill('欧姆定律');
  await expect(page.getByRole('heading',{name:'第一章',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'知识体系',exact:true}).click();
  await expect(page.getByRole('heading',{name:'欧姆定律',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'备份与导出',exact:true}).click();
  const exportPath=resolve(process.cwd(),'../../tmp/e2e-export');
  let exportedDirectory='';
  page.on('dialog',async dialog=>{if(dialog.type()==='prompt')await dialog.accept(exportPath);else {exportedDirectory=dialog.message().split('\n').at(-1)||'';await dialog.accept();}});
  await page.getByRole('button',{name:'选择导出位置'}).click();
  await expect(page.getByRole('status')).toContainText('导出已完成');
  const exportedNotes=await readdir(resolve(exportedDirectory,'笔记'));
  const exportedBody=await readFile(resolve(exportedDirectory,'笔记',exportedNotes[0]),'utf8');
  expect(exportedBody).toContain(`**${original}**`);
  expect(exportedBody).toContain('欧姆定律');
  expect(exportedBody).toContain(`- [x] ${todo}`);
  expect(errors).toEqual([]);
});
